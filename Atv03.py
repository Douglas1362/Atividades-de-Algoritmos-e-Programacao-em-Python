# 3. Antecessor e sucessor 
# Leia um número inteiro e mostre: 
# ● o número informado; 
# ● seu antecessor; 
# ● seu sucessor; 
# ● o dobro; 
# ● o triplo. 

numero = int(input("Digite um número inteiro: "))

antecessor = numero - 1
sucessor = numero + 1
dobro =  numero * 2
triplo = numero * 3

print("Número: ", numero)
print("Antecessor: ", antecessor)
print("Sucessor: ", sucessor)
print("Dobro: ", dobro)
print("Triplo: ", triplo)